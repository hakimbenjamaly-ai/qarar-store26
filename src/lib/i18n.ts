/** يختار الحقل الإنجليزي إن وُجد، وإلا العربي (المحتوى الإنجليزي اختياري) */
export function pick(l: Locale, ar: string | null | undefined, en: string | null | undefined) {
  return l === "en" && en && en.trim() ? en : (ar ?? "");
}

export function money(n: number | string | { toString(): string } | null | undefined, l: Locale) {
  if (n === null || n === undefined) return "—";
  const v = Number(n.toString());
  return l === "en"
    ? `${v.toLocaleString("en-US", { maximumFractionDigits: 2 })} LYD`
    : `${v.toLocaleString("ar-LY", { maximumFractionDigits: 2 })} د.ل`;
}

export function dateTimeL(d: Date | null | undefined, l: Locale) {
  if (!d) return "—";
  return d.toLocaleString(l === "en" ? "en-GB" : "ar-LY", { timeZone: "Africa/Tripoli", dateStyle: "medium", timeStyle: "short" });
}

export function dateL(d: Date | null | undefined, l: Locale) {
  if (!d) return "—";
  return d.toLocaleDateString(l === "en" ? "en-GB" : "ar-LY", { timeZone: "Africa/Tripoli", dateStyle: "medium" });
}
